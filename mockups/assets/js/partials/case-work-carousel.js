/* Native scrolling keeps every project accessible without JavaScript. */
(() => {
  const reduced = matchMedia("(prefers-reduced-motion: reduce)");
  document.querySelectorAll("[data-work-carousel]").forEach((section) => {
    const track = section.querySelector(".case-work-track");
    const originals = [...track.children];
    // Copies either side let the final card flow back into the first one.
    function copies() {
      return originals.map((item) => {
        const clone = item.cloneNode(true);
        clone.setAttribute("aria-hidden", "true");
        clone.querySelectorAll("a").forEach((link) => (link.tabIndex = -1));
        return clone;
      });
    }
    track.prepend(...copies());
    track.append(...copies());
    let touching = false;
    let settling;

    let visible = false;
    let hovered = false;
    let timer;
    const step = () =>
      track.children[1].offsetLeft - track.children[0].offsetLeft;
    const cycle = () => step() * originals.length;
    function normalize() {
      if (drag) return;
      const length = cycle();
      if (!length) return;
      if (track.scrollLeft < length - 2)
        track.scrollTo({
          left: track.scrollLeft + length,
          behavior: "instant",
        });
      else if (track.scrollLeft >= length * 2 - 2)
        track.scrollTo({
          left: track.scrollLeft - length,
          behavior: "instant",
        });
    }
    function move(direction) {
      track.scrollTo({
        left: track.scrollLeft + direction * step(),
        behavior: reduced.matches ? "instant" : "smooth",
      });
    }
    function sync() {
      clearInterval(timer);
      const focused =
        section.contains(document.activeElement) &&
        document.activeElement.matches(":focus-visible");
      if (
        !reduced.matches &&
        visible &&
        !hovered &&
        !touching &&
        !focused &&
        !document.hidden
      )
        timer = setInterval(() => move(1), 4500);
    }
    section.querySelector(".case-work-controls").hidden = false;
    section.querySelector("[data-work-prev]").addEventListener("click", () => {
      move(-1);
      sync();
    });
    section.querySelector("[data-work-next]").addEventListener("click", () => {
      move(1);
      sync();
    });
    section.addEventListener("focusin", sync);
    section.addEventListener("focusout", () => setTimeout(sync, 0));
    section.addEventListener("pointerenter", (event) => {
      if (event.pointerType === "mouse") {
        hovered = true;
        sync();
      }
    });
    section.addEventListener("pointerleave", () => {
      hovered = false;
      sync();
    });
    let drag = null;
    let suppressClick = false;
    track.addEventListener("dragstart", (event) => event.preventDefault());
    track.addEventListener("pointerdown", (event) => {
      touching = true;
      sync();
      suppressClick = false;
      if (event.pointerType !== "mouse" || event.button !== 0) return;
      drag = {
        id: event.pointerId,
        x: event.clientX,
        scroll: track.scrollLeft,
        moved: false,
      };
    });
    track.addEventListener("pointermove", (event) => {
      if (!drag || event.pointerId !== drag.id) return;
      const distance = event.clientX - drag.x;
      if (!drag.moved && Math.abs(distance) < 6) return;
      if (!drag.moved) {
        drag.moved = true;
        track.classList.add("is-dragging");
        track.setPointerCapture(event.pointerId);
      }
      event.preventDefault();
      track.scrollLeft = drag.scroll - distance;
    });
    function endDrag(event) {
      touching = false;
      sync();
      if (!drag || event.pointerId !== drag.id) return;
      suppressClick = drag.moved;
      drag = null;
      track.classList.remove("is-dragging");
      if (track.hasPointerCapture(event.pointerId))
        track.releasePointerCapture(event.pointerId);
      // The click generated by pointerup must not open a project after a drag.
      setTimeout(() => {
        suppressClick = false;
      }, 0);
    }
    track.addEventListener("pointerup", endDrag);
    track.addEventListener("pointercancel", endDrag);
    track.addEventListener("lostpointercapture", endDrag);
    track.addEventListener("pointerleave", (event) => {
      if (drag && !drag.moved) endDrag(event);
    });
    track.addEventListener(
      "click",
      (event) => {
        if (suppressClick) {
          event.preventDefault();
          event.stopPropagation();
        }
      },
      true,
    );
    track.addEventListener("wheel", sync, { passive: true });
    track.addEventListener(
      "scroll",
      () => {
        clearTimeout(settling);
        settling = setTimeout(normalize, 160);
      },
      { passive: true },
    );
    new IntersectionObserver(
      ([entry]) => {
        visible = entry.isIntersecting;
        sync();
      },
      { threshold: 0.2 },
    ).observe(section);
    new ResizeObserver(() => {
      track.scrollTo({ left: cycle(), behavior: "instant" });
      sync();
    }).observe(track);
    document.addEventListener("visibilitychange", sync);
    reduced.addEventListener("change", () => {
      if (reduced.matches) {
        track.scrollTo({ left: track.scrollLeft, behavior: "instant" });
        sync();
      }
      sync();
    });
    track.scrollTo({ left: cycle(), behavior: "instant" });
    sync();
  });
})();
